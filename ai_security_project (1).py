from sklearn.metrics import accuracy_score, precision_score, recall_score
from torch.utils.data import DataLoader, Subset, ConcatDataset

def evaluate_discriminator(netD, clean_root, poison_root=None, poison_ratio=0.0,
                            n_samples=500, threshold=0.5):
    """
    Evaluates the discriminator's ability to distinguish real vs fake images.
    Reports Accuracy, Precision, and Recall."""

    netD.eval()

    eval_dataset = dset.ImageFolder(root=clean_root, transform=transform)
    eval_indices = random.sample(range(len(eval_dataset)), min(n_samples, len(eval_dataset)))
    eval_subset = Subset(eval_dataset, eval_indices)
    eval_loader = DataLoader(eval_subset, batch_size=64, shuffle=False)

    # Fresh generator for fake samples
    netG_eval = Generator(ngpu).to(device)
    netG_eval.apply(weights_init)
    netG_eval.eval()

    y_true, y_pred = [], []

    with torch.no_grad():
        for real_batch, _ in eval_loader:
            real_batch = real_batch.to(device)
            b = real_batch.size(0)

            real_scores = netD(real_batch).view(-1).cpu().numpy()
            y_true.extend([1] * b)
            y_pred.extend((real_scores >= threshold).astype(int).tolist())

            noise = torch.randn(b, nz, 1, 1, device=device)
            fake = netG_eval(noise)
            fake_scores = netD(fake).view(-1).cpu().numpy()
            y_true.extend([0] * b)
            y_pred.extend((fake_scores >= threshold).astype(int).tolist())

    acc  = accuracy_score(y_true, y_pred)
    prec = precision_score(y_true, y_pred, zero_division=0)
    rec  = recall_score(y_true, y_pred, zero_division=0)

    poison_acceptance = None
    if poison_root and os.path.exists(poison_root):
        p_dataset = dset.ImageFolder(root=poison_root, transform=transform)
        p_indices = random.sample(range(len(p_dataset)), min(n_samples, len(p_dataset)))
        p_subset = Subset(p_dataset, p_indices)
        p_loader = DataLoader(p_subset, batch_size=64, shuffle=False)
        accepted = 0
        total = 0
        with torch.no_grad():
            for pb, _ in p_loader:
                pb = pb.to(device)
                scores = netD(pb).view(-1).cpu().numpy()
                accepted += (scores >= threshold).sum()
                total += len(scores)
        poison_acceptance = accepted / total if total > 0 else 0.0

    results = {
        "accuracy":              round(acc,  4),
        "precision":             round(prec, 4),
        "recall":                round(rec,  4),
        "poison_acceptance_rate": round(poison_acceptance, 4) if poison_acceptance is not None else "N/A",
    }
    return results

def spectral_signature_defense(dataset, suspect_fraction=0.1, n_components=10):
    """
    Spectral Signatures Defense

    Detects and removes poisoned samples by looking for outliers in the
    top singular vectors of the feature representation of the dataset.
    Poisoned samples cluster differently in this subspace."""

    print("Running Spectral Signature Defense...")

    loader = DataLoader(dataset, batch_size=64, shuffle=False)
    features = []

    for imgs, _ in loader:
        flat = imgs.view(imgs.size(0), -1).numpy()
        features.append(flat)

    features = np.concatenate(features, axis=0)
    print(f"  Feature matrix: {features.shape}")

    mean = features.mean(axis=0, keepdims=True)
    centered = features - mean

    _, _, Vt = np.linalg.svd(centered, full_matrices=False)
    top_V = Vt[:n_components]

    projections = centered @ top_V.T
    scores = (projections ** 2).sum(axis=1)

    n_remove = int(len(scores) * suspect_fraction)
    flagged_idx = np.argsort(scores)[-n_remove:]
    clean_idx = np.setdiff1d(np.arange(len(scores)), flagged_idx)

    print(f"  Total samples : {len(scores):,}")
    print(f"  Flagged (removed): {len(flagged_idx):,}  ({suspect_fraction:.0%})")
    print(f"  Retained (clean) : {len(clean_idx):,}")

    return clean_idx.tolist(), flagged_idx.tolist()


def build_defended_dataloader(clean_root, poison_root, poison_ratio,
                               suspect_fraction=0.15):
    """
    Builds a dataloader after applying spectral signature defense.
    Combines clean + poisoned data, runs the defense filter,
    then returns a dataloader containing only the retained samples.
    """
    mixed_dataset = build_poisoned_dataset(clean_root, poison_root, poison_ratio)
    clean_idx, removed_idx = spectral_signature_defense(
        mixed_dataset, suspect_fraction=suspect_fraction
    )
    defended_subset = Subset(mixed_dataset, clean_idx)
    return DataLoader(defended_subset, batch_size=batch_size,
                      shuffle=True, num_workers=workers)

